/**
 * Minimal SMTP client (RFC 5321) with STARTTLS (RFC 3207) and AUTH PLAIN /
 * LOGIN (RFC 4954). Enough to hand plain-text mail to any provider that
 * offers SMTP submission. No dependencies.
 *
 * Security rules:
 * - Credentials are only ever sent over TLS. A server that does not offer
 *   STARTTLS on a plain connection is refused unless `allowInsecure` is set,
 *   which exists for a mail catcher on this machine during development.
 * - Certificates are verified (Node's default) against the configured host.
 * - Addresses and the subject cannot carry CR or LF, so a message cannot gain
 *   extra headers or recipients from what people type.
 */

import net from 'node:net';
import tls from 'node:tls';
import crypto from 'node:crypto';

const ADDRESS_RE = /^[^\s<>@",;:\\()[\]\x00-\x1f\x7f]+@[^\s<>@",;:\\()[\]\x00-\x1f\x7f]+\.[^\s<>@",;:\\()[\]\x00-\x1f\x7f]+$/;

export class SmtpError extends Error {
  constructor(message, { code = null, permanent = false } = {}) {
    super(message);
    this.name = 'SmtpError';
    this.code = code;
    // 5xx replies mean "this will not work if you try again".
    this.permanent = permanent;
  }
}

/** "Name <a@b.c>" or "a@b.c" → { name, address }. */
export function parseFrom(value) {
  const text = String(value || '').trim();
  const m = /^(.*?)\s*<([^<>]+)>$/.exec(text);
  const address = (m ? m[2] : text).trim();
  if (!ADDRESS_RE.test(address)) throw new SmtpError('HUSHLIST_MAIL_FROM is not a valid address');
  const name = m ? m[1].replace(/^"|"$/g, '').trim() : '';
  if (/[\r\n]/.test(name)) throw new SmtpError('HUSHLIST_MAIL_FROM is not a valid address');
  return { name, address };
}

/** RFC 2047 encoded-word for header text that is not plain ASCII. */
export function encodeHeader(text) {
  const clean = String(text).replace(/[\r\n]+/g, ' ');
  if (/^[\x20-\x7e]*$/.test(clean)) return clean;
  // Split into chunks of whole characters so each encoded word stays short.
  const words = [];
  let chunk = '';
  for (const ch of clean) {
    if (Buffer.byteLength(chunk + ch) > 45) { words.push(chunk); chunk = ''; }
    chunk += ch;
  }
  if (chunk) words.push(chunk);
  return words.map(w => `=?UTF-8?B?${Buffer.from(w).toString('base64')}?=`).join('\r\n ');
}

function rfc5322Date(date) {
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const p = (n) => String(n).padStart(2, '0');
  return `${days[date.getUTCDay()]}, ${p(date.getUTCDate())} ${months[date.getUTCMonth()]} ${date.getUTCFullYear()} ` +
    `${p(date.getUTCHours())}:${p(date.getUTCMinutes())}:${p(date.getUTCSeconds())} +0000`;
}

/** The full message, CRLF line endings, body base64 so any text is safe on the wire. */
export function buildMessage({ from, to, subject, body, date = new Date(), autoGenerated = true }) {
  const sender = parseFrom(from);
  if (!ADDRESS_RE.test(to)) throw new SmtpError('Recipient address is not valid', { permanent: true });
  const domain = sender.address.split('@')[1];
  const fromHeader = sender.name ? `${encodeHeader(sender.name.replace(/"/g, ''))} <${sender.address}>` : sender.address;
  const encodedBody = Buffer.from(String(body).replace(/\r?\n/g, '\r\n'), 'utf8').toString('base64').replace(/.{1,76}/g, '$&\r\n');
  const headers = [
    `From: ${fromHeader}`,
    `To: ${to}`,
    `Subject: ${encodeHeader(subject)}`,
    `Date: ${rfc5322Date(date)}`,
    `Message-ID: <${crypto.randomBytes(12).toString('hex')}@${domain}>`,
    'MIME-Version: 1.0',
    'Content-Type: text/plain; charset=utf-8',
    'Content-Transfer-Encoding: base64',
    ...(autoGenerated ? ['Auto-Submitted: auto-generated'] : [])
  ];
  return { envelopeFrom: sender.address, data: `${headers.join('\r\n')}\r\n\r\n${encodedBody}` };
}

/** Reads SMTP replies ("250-…" continued, "250 …" final) from a socket. */
function replyReader(getSocket) {
  let buffer = '';
  let waiting = null;
  const lines = [];
  const onData = (chunk) => {
    buffer += chunk.toString('utf8');
    if (buffer.length > 64 * 1024) { buffer = ''; fail(new SmtpError('SMTP reply too long')); return; }
    let idx;
    while ((idx = buffer.indexOf('\n')) !== -1) {
      lines.push(buffer.slice(0, idx).replace(/\r$/, ''));
      buffer = buffer.slice(idx + 1);
    }
    flush();
  };
  let failure = null;
  const fail = (err) => { failure = err; if (waiting) { const w = waiting; waiting = null; w.reject(err); } };
  const flush = () => {
    if (!waiting) return;
    const end = lines.findIndex(l => /^\d{3}(?: |$)/.test(l));
    if (end === -1) return;
    const reply = lines.splice(0, end + 1);
    const code = Number(reply[end].slice(0, 3));
    const w = waiting; waiting = null;
    w.resolve({ code, lines: reply.map(l => l.slice(4)) });
  };
  return {
    attach(socket) {
      socket.on('data', onData);
      socket.on('error', (err) => fail(new SmtpError(`SMTP connection failed: ${err.message}`)));
      socket.on('close', () => fail(new SmtpError('SMTP connection closed')));
      socket.on('timeout', () => { fail(new SmtpError('SMTP server did not answer in time')); socket.destroy(); });
    },
    detach(socket) { socket.removeAllListeners('data'); socket.removeAllListeners('error'); socket.removeAllListeners('close'); socket.removeAllListeners('timeout'); },
    next() {
      if (failure) return Promise.reject(failure);
      return new Promise((resolve, reject) => { waiting = { resolve, reject }; flush(); });
    },
    socket: getSocket
  };
}

/**
 * Returns an async send({ to, subject, body }) function.
 * One connection per message: simple, and mail volume here is small.
 */
export function createSmtpTransport({
  host, port = 587, secure = port === 465, user = '', pass = '', from,
  heloName = 'hushlist.localhost', timeoutMs = 20_000, allowInsecure = false, tlsOptions = {}
}) {
  if (!host) throw new SmtpError('HUSHLIST_SMTP_HOST is required for SMTP delivery');
  parseFrom(from); // fail at start-up, not at the first message

  return async function send({ to, subject, body, eventType }) {
    const message = buildMessage({ from, to, subject, body, autoGenerated: eventType !== undefined });
    let socket = secure
      ? tls.connect({ host, port, servername: net.isIP(host) ? undefined : host, ...tlsOptions })
      : net.connect({ host, port });
    socket.setTimeout(timeoutMs);
    let reader = replyReader();
    reader.attach(socket);

    const command = async (line, expect, { secret = false, label = null } = {}) => {
      if (line !== null) socket.write(`${line}\r\n`);
      const reply = await reader.next();
      if (!expect.includes(Math.floor(reply.code / 100) * 100) && !expect.includes(reply.code)) {
        // Never echo credentials or message text into an error (and so a log).
        const shown = secret ? '(authentication)' : (label || (line === null ? 'greeting' : line.split(' ')[0]));
        throw new SmtpError(`SMTP server refused ${shown}: ${reply.code} ${reply.lines.join(' ').slice(0, 200)}`,
          { code: reply.code, permanent: reply.code >= 500 });
      }
      return reply;
    };

    try {
      await command(null, [200]);
      let ehlo = await command(`EHLO ${heloName}`, [200]);
      const isTls = () => socket instanceof tls.TLSSocket;
      if (!isTls()) {
        const offersStartTls = ehlo.lines.some(l => /^STARTTLS\b/i.test(l));
        if (offersStartTls) {
          await command('STARTTLS', [200]);
          reader.detach(socket);
          socket = await new Promise((resolve, reject) => {
            const secured = tls.connect({ socket, servername: net.isIP(host) ? undefined : host, ...tlsOptions }, () => resolve(secured));
            secured.once('error', reject);
          });
          socket.setTimeout(timeoutMs);
          reader = replyReader();
          reader.attach(socket);
          ehlo = await command(`EHLO ${heloName}`, [200]);
        } else if (!allowInsecure) {
          throw new SmtpError('SMTP server does not offer STARTTLS; refusing to send without encryption');
        }
      }

      if (user) {
        if (!isTls() && !allowInsecure) throw new SmtpError('Refusing to send SMTP credentials without TLS');
        const auth = ehlo.lines.find(l => /^AUTH\b/i.test(l)) || '';
        if (/\bPLAIN\b/i.test(auth)) {
          await command(`AUTH PLAIN ${Buffer.from(`\0${user}\0${pass}`).toString('base64')}`, [235], { secret: true });
        } else if (/\bLOGIN\b/i.test(auth)) {
          await command('AUTH LOGIN', [334], { secret: true });
          await command(Buffer.from(user).toString('base64'), [334], { secret: true });
          await command(Buffer.from(pass).toString('base64'), [235], { secret: true });
        } else {
          throw new SmtpError('SMTP server offers no supported sign-in method (PLAIN or LOGIN)');
        }
      }

      await command(`MAIL FROM:<${message.envelopeFrom}>`, [200], { label: 'MAIL FROM' });
      await command(`RCPT TO:<${to}>`, [200], { label: 'RCPT TO' });
      await command('DATA', [354]);
      // Dot-stuffing: a line that starts with "." gets another one. The
      // message already ends with CRLF, so "." on its own line ends it.
      const payload = message.data.replace(/(^|\r\n)\./g, '$1..');
      await command(`${payload}.`, [200], { label: 'message' });
      try { await command('QUIT', [200]); } catch { /* the message is already accepted */ }
    } finally {
      socket.destroy();
    }
  };
}
